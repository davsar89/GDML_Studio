import { useAppStore } from '../../store';
import type { NistMaterial } from '../../store/types';
import * as api from '../../api/client';
import { prepareNistMaterial } from '../../utils/nistImport';
import { refreshMaterialsAndScene } from '../../utils/refresh';
import { runDocumentAction, resolveMaterialDraft } from '../../utils/documentActions';
import SearchableCombobox from '../SearchableCombobox';

export default function VolumeDetail() {
  const selectedVolume = useAppStore((s) => s.selectedVolume);
  const volumes = useAppStore((s) => s.volumes);
  const materials = useAppStore((s) => s.materials);
  const busy = useAppStore((s) => s.documentBusy);

  if (!selectedVolume) return null;

  const vol = volumes.find((v) => v.name === selectedVolume);
  if (!vol) return <p className="field-hint">{selectedVolume} is generated by a &lt;loop&gt;; edit the loop in the source file.</p>;

  const mat = materials.find((m) => m.name === vol.material_ref);

  const handleMaterialSelect = async (name: string, nist?: NistMaterial) => {
    if (name === vol.material_ref) return;
    await runDocumentAction(async () => {
      if (!await resolveMaterialDraft()) return;
      try {
        if (nist) {
          // Auto-import from NIST under its own name, then assign
          const { material, elements } = await prepareNistMaterial(nist);
          await api.addMaterial(material, elements);
        }
        await api.updateVolumeMaterialRef(vol.name, name);
      } finally {
        // Even a half-done NIST pick may have added the material.
        await refreshMaterialsAndScene();
      }
    });
  };

  return (
    <fieldset disabled={busy}>
      <h3 className="editor-title">{vol.name}</h3>
      <dl className="properties">
        <dt>Solid</dt><dd>{vol.solid_ref || 'Assembly'}</dd>
      </dl>
      {vol.solid_ref && <SearchableCombobox value={vol.material_ref} materials={materials} onChange={handleMaterialSelect} />}
      {mat && <div className="material-summary">
        <dl className="properties">
          {mat.density != null && <><dt>Density</dt><dd>{mat.density.value} {mat.density.unit || 'g/cm3'}</dd></>}
          {mat.formula && <><dt>Formula</dt><dd>{mat.formula}</dd></>}
          {mat.z != null && <><dt>Atomic number</dt><dd>{mat.z}</dd></>}
        </dl>
        <button onClick={() => {
          useAppStore.getState().setSelectedMaterial(vol.material_ref);
          useAppStore.getState().setActiveTreeTab('materials');
        }}>Edit material</button>
      </div>}
    </fieldset>
  );
}
